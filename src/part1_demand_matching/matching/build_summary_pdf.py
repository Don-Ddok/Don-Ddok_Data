def P(t, s="p"):
    return Paragraph(t, ST[s])


def bullets(items):
    return [Paragraph(t, ST["b"], bulletText="•") for t in items]


def table(rows, widths, header=True, zebra=True):
    data = [[P(str(c), "cellh" if (header and i == 0) else "cell") for c in r] for i, r in enumerate(rows)]
    t = Table(data, colWidths=[w * mm for w in widths], repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor(GRID)),
             ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
             ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4)]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f0efec")))
    if zebra:
        for i in range(2 if header else 1, len(rows), 2):
            style.append(("BACKGROUND", (0, i), (-1, i), colors.HexColor("#f8f8f6")))
    t.setStyle(TableStyle(style))
    return t


def trigger_chart():
    """지역별 소형 다중 차트: 보정 수출 YoY 선 + 둔화(회색)·적기(연파랑) 음영. 한 패널에 선 하나라 범례 없음."""
    font_manager.fontManager.addfont(FONT)
    plt.rcParams["font.family"] = font_manager.FontProperties(fname=FONT).get_name()
    plt.rcParams["axes.unicode_minus"] = False
    d = pd.read_csv(os.path.join(BASE, "trigger_stages.csv"))
    fig, axes = plt.subplots(2, 1, figsize=(7.2, 4.6), sharex=True, facecolor=SURFACE)
    for ax, reg in zip(axes, ["경북", "대구"]):
        g = d[d["지역"] == reg].reset_index(drop=True)
        x = range(len(g))
        ax.set_facecolor(SURFACE)
        for i, r in g.iterrows():
            if r["둔화여부"]:
                ax.axvspan(i - 0.5, i + 0.5, color="#ebeae6", lw=0, zorder=0)
            if r["단계"] == "적기":
                ax.axvspan(i - 0.5, i + 0.5, color=BLUE_100, lw=0, zorder=0.5)
        ax.axhline(0, color=MUTED, lw=0.8, zorder=1)
        ax.plot(list(x), g["보정YoY"], color=BLUE, lw=2, zorder=2)
        ax.set_ylabel("보정 수출 YoY (%)", fontsize=8, color=INK2)
        ax.set_title(reg, loc="left", fontsize=10, color=INK, fontweight="bold")
        ax.grid(axis="y", color=GRID, lw=0.6)
        for s in ["top", "right", "left"]:
            ax.spines[s].set_visible(False)
        ax.spines["bottom"].set_color(GRID)
        ax.tick_params(colors=INK2, labelsize=7.5, length=0)
    labels = [f"{str(m)[2:4]}.{str(m)[4:]}" for m in d[d["지역"] == "경북"]["연월"]]
    axes[1].set_xticks(range(0, len(labels), 3))
    axes[1].set_xticklabels(labels[::3])
    fig.tight_layout()
    fig.savefig(CHART, dpi=200, facecolor=SURFACE)
    plt.close(fig)


